/**
 * 待ち受け側が返すHTTPステータスを、利用者が次に何をすればよいか分かる日本語にする。
 *
 * ステータスを見ずに本文をそのまま復号にかけると、409/413/504 の本文（プレーンテキスト）が
 * JSONとして壊れているために「鍵が合いません。QRを読み直してください。」と案内されてしまう。
 * 原因と無関係な案内なので、利用者はQRを読み直しても解決しない。
 *
 * PC版・Android版の双方がこの1箇所を使う（文言が2箇所に分かれて食い違うのを防ぐ）。
 */
export function describeSyncStatus(status: number): string {
  switch (status) {
    case 400:
      return '相手の端末が受け取りに失敗しました。QRを表示し直して、もう一度お試しください。';
    case 404:
      return '相手の端末が連携を待っていません。QRを表示し直してください。';
    case 409:
      return 'この連携は既に使われています。QRを表示し直してください。';
    case 413:
      return 'データが大きすぎて送れませんでした。ファイルでのやり取りをお使いください。';
    case 503:
      return '相手の端末が連携を中断しました。QRを表示し直してください。';
    case 504:
      return '相手の端末の処理が時間内に終わりませんでした。もう一度お試しください。';
    default:
      return `相手の端末がエラーを返しました（${status}）。QRを表示し直してください。`;
  }
}
